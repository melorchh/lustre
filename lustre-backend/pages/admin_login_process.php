<?php
require __DIR__ . '/../src/session.php';
require_once __DIR__ . '/../src/db.php';
require_once __DIR__ . '/../src/staff_auth.php';

header('Content-Type: text/plain; charset=utf-8');

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(400);
    echo "Invalid request";
    $conn->close();
    exit;
}

$username = isset($_POST['username']) ? trim($_POST['username']) : '';
$password = isset($_POST['password']) ? $_POST['password'] : '';
$action = isset($_POST['action']) ? trim($_POST['action']) : '';

if ($action === 'cancel_otp') {
    unset($_SESSION['admin_login_pending']);
    echo 'success';
    $conn->close();
    exit;
}

if ($username === '' || $password === '') {
    echo "Username and password are required";
    $conn->close();
    exit;
}

$result = verify_admin_login($conn, $username, $password, false);
if (!$result['found'] || !$result['ok']) {
    echo $result['msg'];
    $conn->close();
    exit;
}

if ($action === '') {
    echo 'admin_otp_required';
    $conn->close();
    exit;
}

$admin_id = (int)$result['id'];
$email = trim((string)($result['email'] ?? ''));

if ($action === 'request_otp') {
    if (isset($_SESSION['admin_otp_request_at']) && time() - (int)$_SESSION['admin_otp_request_at'] < 60) {
        echo 'Please wait before requesting another verification code.';
        $conn->close();
        exit;
    }

    $enroll_email = ($email === '');
    if ($enroll_email) {
        $email = trim(isset($_POST['email']) ? $_POST['email'] : '');
        if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
            echo 'email_required';
            $conn->close();
            exit;
        }
        $check = $conn->prepare("SELECT id FROM admin_users WHERE LOWER(email) = LOWER(?) AND id <> ? LIMIT 1");
        $check->bind_param("si", $email, $admin_id);
        $check->execute();
        $check->store_result();
        if ($check->num_rows > 0) {
            $check->close();
            echo 'That email is already assigned to another admin account.';
            $conn->close();
            exit;
        }
        $check->close();
    }

    $conn->query("CREATE TABLE IF NOT EXISTS admin_login_tokens (
        id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        admin_id   INTEGER NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
        email      VARCHAR(255) NOT NULL,
        token      VARCHAR(64) NOT NULL,
        expires_at TIMESTAMP NOT NULL,
        used       SMALLINT NOT NULL DEFAULT 0,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )");
    $rotate = $conn->prepare("UPDATE admin_login_tokens SET used = 1 WHERE admin_id = ? AND used = 0");
    $rotate->bind_param("i", $admin_id);
    if (!$rotate->execute()) {
        $rotate->close();
        echo 'Failed to prepare a verification code. Please try again.';
        $conn->close();
        exit;
    }
    $rotate->close();

    $otp = str_pad((string)random_int(0, 999999), 6, '0', STR_PAD_LEFT);
    $token_hash = hash('sha256', $otp);
    $expires = date('Y-m-d H:i:s', time() + (15 * 60));
    $stmt = $conn->prepare("INSERT INTO admin_login_tokens (admin_id, email, token, expires_at) VALUES (?, ?, ?, ?)");
    $stmt->bind_param("isss", $admin_id, $email, $token_hash, $expires);
    if (!$stmt->execute()) {
        $stmt->close();
        echo 'Failed to prepare a verification code. Please try again.';
        $conn->close();
        exit;
    }
    $stmt->close();

    require_once __DIR__ . '/../src/SMTPMailer.php';
    try {
        $mailer = new SMTPMailer();
        $mailer->send(
            $email,
            'LustreMDC — Admin Login OTP',
            "Hello " . $username . ",\n\nYour admin login verification code is: " . $otp . "\n\nThis code expires in 15 minutes. If you did not attempt to sign in, you can ignore this email.",
            $result['name'] ?? null
        );
        $_SESSION['admin_login_pending'] = array(
            'admin_id' => $admin_id,
            'username' => $username,
            'email' => $email,
            'enroll_email' => $enroll_email,
            'must_change' => (int)$result['must_change'],
            'otp_attempts' => 0,
        );
        $_SESSION['admin_otp_request_at'] = time();
        echo 'otp_sent';
    } catch (Exception $e) {
        $disable = $conn->prepare("UPDATE admin_login_tokens SET used = 1 WHERE admin_id = ? AND token = ?");
        $disable->bind_param("is", $admin_id, $token_hash);
        $disable->execute();
        $disable->close();
        error_log('Admin OTP SMTP failed: ' . $e->getMessage());
        echo 'Failed to send the verification email. Please try again.';
    }
    $conn->close();
    exit;
}

if ($action === 'verify_otp') {
    $pending = $_SESSION['admin_login_pending'] ?? null;
    if (!$pending || (int)$pending['admin_id'] !== $admin_id || $pending['username'] !== $username) {
        echo 'Session expired. Please sign in again.';
        $conn->close();
        exit;
    }
    $otp = trim(isset($_POST['otp']) ? $_POST['otp'] : '');
    if (!preg_match('/^\d{6}$/', $otp)) {
        echo 'Verification code must be exactly 6 digits.';
        $conn->close();
        exit;
    }
    if (++$pending['otp_attempts'] > 10) {
        unset($_SESSION['admin_login_pending']);
        echo 'Too many failed attempts. Please sign in again.';
        $conn->close();
        exit;
    }
    $_SESSION['admin_login_pending'] = $pending;

    if (empty($pending['enroll_email']) && strcasecmp(trim((string)($result['email'] ?? '')), $pending['email']) !== 0) {
        unset($_SESSION['admin_login_pending']);
        echo 'The admin email changed during verification. Please sign in again.';
        $conn->close();
        exit;
    }

    $token_hash = hash('sha256', $otp);
    $check = $conn->prepare("SELECT id FROM admin_login_tokens WHERE admin_id = ? AND email = ? AND token = ? AND used = 0 AND expires_at > NOW() ORDER BY id DESC LIMIT 1");
    $check->bind_param("iss", $admin_id, $pending['email'], $token_hash);
    $check->execute();
    $check->store_result();
    if ($check->num_rows === 0) {
        $check->close();
        echo 'Invalid or expired verification code. Please try again.';
        $conn->close();
        exit;
    }
    $check->close();

    if (!empty($pending['enroll_email'])) {
        $save_email = $conn->prepare("UPDATE admin_users SET email = ? WHERE id = ? AND (email IS NULL OR email = '')");
        $save_email->bind_param("si", $pending['email'], $admin_id);
        if (!$save_email->execute()) {
            $save_email->close();
            echo 'Failed to save the admin email. Please try again.';
            $conn->close();
            exit;
        }
        $save_email->close();
        $confirm_email = $conn->prepare("SELECT email FROM admin_users WHERE id = ?");
        $confirm_email->bind_param("i", $admin_id);
        $confirm_email->execute();
        $confirm_email->bind_result($saved_email);
        $confirm_email->fetch();
        $confirm_email->close();
        if (strcasecmp((string)$saved_email, $pending['email']) !== 0) {
            echo 'The admin email changed during verification. Please sign in again.';
            $conn->close();
            exit;
        }
    }

    $consume = $conn->prepare("UPDATE admin_login_tokens SET used = 1 WHERE admin_id = ? AND email = ? AND token = ? AND used = 0");
    $consume->bind_param("iss", $admin_id, $pending['email'], $token_hash);
    if (!$consume->execute() || $consume->affected_rows !== 1) {
        $consume->close();
        echo 'This verification code has already been used. Please sign in again.';
        $conn->close();
        exit;
    }
    $consume->close();

    unset($_SESSION['patient_id'], $_SESSION['just_registered']);
    unset($_SESSION['doctor_account_id'], $_SESSION['doctor_id'], $_SESSION['doctor_name'], $_SESSION['doctor_username']);
    $_SESSION['admin_id'] = $admin_id;
    $_SESSION['admin_name'] = $result['name'];
    $_SESSION['admin_username'] = $username;
    $_SESSION['admin_email'] = $pending['email'];
    $_SESSION['admin_must_change'] = (int)$pending['must_change'];
    unset($_SESSION['admin_login_pending'], $_SESSION['admin_otp_request_at']);
    echo $_SESSION['admin_must_change'] ? 'change_password' : 'success';
    $conn->close();
    exit;
}

echo 'Invalid request';

$conn->close();
?>
