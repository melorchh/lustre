<?php
require __DIR__ . '/../src/session.php';
require_once __DIR__ . '/../src/db.php';
require_once __DIR__ . '/../src/staff_auth.php';

header('Content-Type: text/plain; charset=utf-8');

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    echo "Invalid request";
    exit;
}

$username = isset($_POST['username']) ? trim($_POST['username']) : '';
$password = isset($_POST['password']) ? $_POST['password'] : '';
$action   = isset($_POST['action']) ? trim($_POST['action']) : '';

if ($action === 'cancel_otp') {
    unset($_SESSION['doctor_login_pending']);
    echo 'success';
    $conn->close();
    exit;
}

if (empty($username) || empty($password)) {
    echo "Username and password are required";
    exit;
}

// Ensure tables
ensure_doctor_accounts_table($conn);
$conn->query("CREATE TABLE IF NOT EXISTS email_tokens (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL,
    token      VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMP    NOT NULL,
    used       SMALLINT     NOT NULL DEFAULT 0,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
)");

// Fetch doctor account
$stmt = $conn->prepare(
    "SELECT da.id, da.doctor_id, da.password, da.email, d.name
     FROM doctor_accounts da
     JOIN doctors d ON da.doctor_id = d.id
     WHERE da.username = ?"
);
$stmt->bind_param("s", $username);
$stmt->execute();
$stmt->store_result();

if ($stmt->num_rows === 0) {
    $stmt->close();
    echo "Invalid username or password";
    $conn->close();
    exit;
}

$stmt->bind_result($account_id, $doctor_id, $hashed_password, $email, $doctor_name);
$stmt->fetch();
$stmt->close();

if (!password_verify($password, $hashed_password)) {
    echo "Invalid username or password";
    $conn->close();
    exit;
}

if ($action === 'request_otp') {
    if (empty($email) || !filter_var($email, FILTER_VALIDATE_EMAIL)) {
        echo "No email configured for this doctor account. Please contact the administrator.";
        $conn->close();
        exit;
    }

    // Invalidate existing unused tokens for this email
    $conn->prepare("UPDATE email_tokens SET used = 1 WHERE email = ? AND used = 0")->execute([$email]);

    // Generate OTP
    $otp = str_pad((string)random_int(0, 999999), 6, '0', STR_PAD_LEFT);
    $token_hash = hash('sha256', $otp);
    $expires = date('Y-m-d H:i:s', time() + (15 * 60));

    $stmtOtp = $conn->prepare("INSERT INTO email_tokens (email, token, expires_at, used) VALUES (?, ?, ?, 0)");
    $stmtOtp->bind_param("sss", $email, $token_hash, $expires);
    if (!$stmtOtp->execute()) {
        $stmtOtp->close();
        echo "Failed to send OTP. Please try again.";
        $conn->close();
        exit;
    }
    $stmtOtp->close();

    // Send email
    $subject = 'LustreMDC — Doctor Login OTP';
    $message = "Hello Dr. " . $doctor_name . ",\n\n"
        . "Your login verification code is: " . $otp . "\n\n"
        . "This code will expire in 15 minutes.\n"
        . "If you did not attempt to log in, please ignore this email.\n\n"
        . "— LustreMDC Clinics & Diagnostics";

    require_once __DIR__ . '/../src/SMTPMailer.php';

    try {
        $mail = new SMTPMailer();
        $mail->send($email, $subject, $message, $doctor_name);
        $_SESSION['doctor_login_pending'] = array(
            'account_id' => $account_id,
            'doctor_id'  => $doctor_id,
            'username'   => $username,
            'doctor_name'=> $doctor_name,
            'email'      => $email,
            'otp_attempts' => 0
        );
        echo "otp_sent:" . $doctor_name;
    } catch (Exception $e) {
        error_log("Doctor OTP SMTP failed: " . $e->getMessage());
        echo "Failed to send the verification email. Please try again.";
    }

    $conn->close();
    exit;
}

if ($action === 'verify_otp') {
    if (!isset($_SESSION['doctor_login_pending'])) {
        echo "Session expired. Please login again.";
        $conn->close();
        exit;
    }
    $pending = $_SESSION['doctor_login_pending'];
    if ($pending['account_id'] != $account_id || $pending['username'] !== $username) {
        echo "Session expired. Please login again.";
        $conn->close();
        exit;
    }

    $otp = isset($_POST['otp']) ? trim($_POST['otp']) : '';
    if (!preg_match('/^\d{6}$/', $otp)) {
        echo "Verification code must be exactly 6 digits";
        $conn->close();
        exit;
    }

    if (++$pending['otp_attempts'] > 10) {
        unset($_SESSION['doctor_login_pending']);
        echo "Too many failed attempts. Please login again.";
        $conn->close();
        exit;
    }
    $_SESSION['doctor_login_pending'] = $pending;

    $token_hash = hash('sha256', $otp);
    $stmtCheck = $conn->prepare(
        "SELECT id FROM email_tokens
         WHERE email = ? AND token = ? AND used = 0 AND expires_at > NOW()
         ORDER BY id DESC LIMIT 1"
    );
    $stmtCheck->bind_param("ss", $email, $token_hash);
    $stmtCheck->execute();
    $stmtCheck->store_result();

    if ($stmtCheck->num_rows === 0) {
        $stmtCheck->close();
        echo "Invalid or expired verification code. Please try again.";
        $conn->close();
        exit;
    }
    $stmtCheck->close();

    $stmtConsume = $conn->prepare("UPDATE email_tokens SET used = 1 WHERE email = ? AND token = ? AND used = 0");
    $stmtConsume->bind_param("ss", $email, $token_hash);
    $stmtConsume->execute();
    $stmtConsume->close();

    unset($_SESSION['patient_id'], $_SESSION['just_registered']);
    unset($_SESSION['admin_id'], $_SESSION['admin_name'], $_SESSION['admin_username'], $_SESSION['admin_must_change']);
    $_SESSION['doctor_account_id'] = $account_id;
    $_SESSION['doctor_id']         = $doctor_id;
    $_SESSION['doctor_name']       = $doctor_name;
    $_SESSION['doctor_username']   = $username;
    unset($_SESSION['doctor_login_pending']);

    echo "success";
    $conn->close();
    exit;
}

echo "Invalid request";
$conn->close();
?>
