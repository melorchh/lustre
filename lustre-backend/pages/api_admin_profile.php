<?php
require_once __DIR__ . '/../src/api.php';
require_once __DIR__ . '/../src/staff_auth.php';

$admin_id = api_require_admin();
if (!ensure_admin_email_column($conn)) {
    api_fail('Unable to load admin account settings.', 500);
}

if (($_SERVER['REQUEST_METHOD'] ?? '') === 'GET') {
    $stmt = $conn->prepare("SELECT email FROM admin_users WHERE id = ?");
    $stmt->bind_param("i", $admin_id);
    if (!$stmt->execute()) {
        $stmt->close();
        api_fail('Unable to load admin account settings.', 500);
    }
    $stmt->bind_result($email);
    $stmt->fetch();
    $stmt->close();
    api_ok(array('email' => (string)($email ?? '')));
}

if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') {
    api_fail('Method not allowed', 405);
}

$current = api_post_str('current_password');
$email = strtolower(api_post_str('email'));
$new = api_post_str('new_password');
$confirm = api_post_str('confirm_password');
$action = api_post_str('action', 'save');

if ($current === '' || !filter_var($email, FILTER_VALIDATE_EMAIL)) {
    api_fail('Enter your current password and a valid email address.');
}
if (($new !== '' || $confirm !== '') && ($new === '' || $confirm === '')) {
    api_fail('Enter and confirm the new password.');
}
if ($new !== '' && $new !== $confirm) {
    api_fail('New password and confirmation do not match.');
}
if ($new !== '' && (strlen($new) < 8 || !preg_match('/[A-Za-z]/', $new) || !preg_match('/[0-9]/', $new))) {
    api_fail('New password must be at least 8 characters and contain letters and numbers.');
}

$stmt = $conn->prepare("SELECT password, email FROM admin_users WHERE id = ?");
$stmt->bind_param("i", $admin_id);
if (!$stmt->execute()) {
    $stmt->close();
    api_fail('Unable to verify your current password.', 500);
}
$stmt->store_result();
if ($stmt->num_rows === 0) {
    $stmt->close();
    api_fail('Admin account not found.', 404);
}
$stmt->bind_result($stored_password, $current_email);
$stmt->fetch();
$stmt->close();

$is_hash = preg_match('/^\$2[aby]\$/', $stored_password) === 1;
$current_ok = $is_hash ? password_verify($current, $stored_password) : hash_equals($stored_password, $current);
if (!$current_ok) {
    api_fail('Current password is incorrect.');
}
if ($new !== '' && (($is_hash && password_verify($new, $stored_password)) || (!$is_hash && hash_equals($stored_password, $new)))) {
    api_fail('New password must be different from the current password.');
}

$duplicate = $conn->prepare("SELECT id FROM admin_users WHERE LOWER(email) = LOWER(?) AND id <> ? LIMIT 1");
$duplicate->bind_param("si", $email, $admin_id);
if (!$duplicate->execute()) {
    $duplicate->close();
    api_fail('Unable to validate the email address.', 500);
}
$duplicate->store_result();
if ($duplicate->num_rows > 0) {
    $duplicate->close();
    api_fail('That email is already assigned to another admin account.');
}
$duplicate->close();

if ($action === 'request_email_change') {
    if (strcasecmp($email, (string)$current_email) === 0) {
        api_fail('That is already your current email address.');
    }
    if (isset($_SESSION['admin_profile_otp_requested_at']) && time() - (int)$_SESSION['admin_profile_otp_requested_at'] < 60) {
        api_fail('Please wait before requesting another verification code.');
    }

    $conn->query("CREATE TABLE IF NOT EXISTS admin_email_change_tokens (
        id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        admin_id   INTEGER NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
        email      VARCHAR(255) NOT NULL,
        token      VARCHAR(64) NOT NULL,
        expires_at TIMESTAMP NOT NULL,
        used       SMALLINT NOT NULL DEFAULT 0,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )");
    $rotate = $conn->prepare("UPDATE admin_email_change_tokens SET used = 1 WHERE admin_id = ? AND used = 0");
    $rotate->bind_param("i", $admin_id);
    if (!$rotate->execute()) {
        $rotate->close();
        api_fail('Unable to prepare email verification. Please try again.', 500);
    }
    $rotate->close();

    $otp = str_pad((string)random_int(0, 999999), 6, '0', STR_PAD_LEFT);
    $token_hash = hash('sha256', $otp);
    $expires = date('Y-m-d H:i:s', time() + (15 * 60));
    $token = $conn->prepare("INSERT INTO admin_email_change_tokens (admin_id, email, token, expires_at) VALUES (?, ?, ?, ?)");
    $token->bind_param("isss", $admin_id, $email, $token_hash, $expires);
    if (!$token->execute()) {
        $token->close();
        api_fail('Unable to prepare email verification. Please try again.', 500);
    }
    $token->close();

    require_once __DIR__ . '/../src/SMTPMailer.php';
    try {
        $mailer = new SMTPMailer();
        $mailer->send(
            $email,
            'LustreMDC — Confirm Admin Email Change',
            "Your verification code is: " . $otp . "\n\nThis code expires in 15 minutes. If you did not request this change, you can ignore this email.",
            (string)($_SESSION['admin_name'] ?? '')
        );
        $_SESSION['admin_profile_otp_pending'] = array('admin_id' => $admin_id, 'email' => $email, 'attempts' => 0);
        $_SESSION['admin_profile_otp_requested_at'] = time();
        api_ok(array('otp_required' => true, 'email' => $email));
    } catch (Exception $e) {
        $disable = $conn->prepare("UPDATE admin_email_change_tokens SET used = 1 WHERE admin_id = ? AND token = ?");
        $disable->bind_param("is", $admin_id, $token_hash);
        $disable->execute();
        $disable->close();
        error_log('Admin email OTP SMTP failed: ' . $e->getMessage());
        api_fail('Failed to send the verification email. Please try again.', 502);
    }
}

if ($action === 'verify_email_change') {
    $pending = $_SESSION['admin_profile_otp_pending'] ?? null;
    if (!$pending || (int)$pending['admin_id'] !== $admin_id || strcasecmp($pending['email'], $email) !== 0) {
        api_fail('Email verification expired. Please start again.');
    }
    $otp = api_post_str('otp');
    if (!preg_match('/^\d{6}$/', $otp)) {
        api_fail('Enter the 6-digit verification code.');
    }
    if (++$pending['attempts'] > 10) {
        unset($_SESSION['admin_profile_otp_pending'], $_SESSION['admin_profile_otp_requested_at']);
        api_fail('Too many failed attempts. Please request a new code.');
    }
    $_SESSION['admin_profile_otp_pending'] = $pending;

    $token_hash = hash('sha256', $otp);
    $check = $conn->prepare("SELECT id FROM admin_email_change_tokens WHERE admin_id = ? AND email = ? AND token = ? AND used = 0 AND expires_at > NOW() ORDER BY id DESC LIMIT 1");
    $check->bind_param("iss", $admin_id, $email, $token_hash);
    if (!$check->execute()) {
        $check->close();
        api_fail('Unable to verify the code. Please try again.', 500);
    }
    $check->store_result();
    if ($check->num_rows === 0) {
        $check->close();
        api_fail('Invalid or expired verification code.');
    }
    $check->bind_result($token_id);
    $check->fetch();
    $check->close();

    $pdo = $conn->getPdo();
    if (!$pdo->beginTransaction()) {
        api_fail('Unable to save admin account settings. Please try again.', 500);
    }
    $consume = $conn->prepare("UPDATE admin_email_change_tokens SET used = 1 WHERE id = ? AND used = 0");
    $consume->bind_param("i", $token_id);
    if (!$consume->execute() || $consume->affected_rows !== 1) {
        $consume->close();
        $pdo->rollBack();
        api_fail('This verification code has already been used.');
    }
    $consume->close();

    if ($new !== '') {
        $hash = password_hash($new, PASSWORD_DEFAULT);
        $update = $conn->prepare("UPDATE admin_users SET email = ?, password = ?, must_change_password = 0, password_changed_at = NOW(), failed_attempts = 0, locked_until = NULL WHERE id = ?");
        $update->bind_param("ssi", $email, $hash, $admin_id);
    } else {
        $update = $conn->prepare("UPDATE admin_users SET email = ? WHERE id = ?");
        $update->bind_param("si", $email, $admin_id);
    }
    if (!$update->execute()) {
        $update->close();
        $pdo->rollBack();
        api_fail('Failed to update admin account. Please try again.', 500);
    }
    $update->close();
    if (!$pdo->commit()) {
        if ($pdo->inTransaction()) {
            $pdo->rollBack();
        }
        api_fail('Failed to save admin account settings. Please try again.', 500);
    }

    $_SESSION['admin_email'] = $email;
    if ($new !== '') {
        $_SESSION['admin_must_change'] = 0;
    }
    unset($_SESSION['admin_profile_otp_pending'], $_SESSION['admin_profile_otp_requested_at']);
    api_ok(array('email' => $email));
}

if ($action !== 'save') {
    api_fail('Invalid account action.');
}
if (strcasecmp($email, (string)$current_email) !== 0) {
    api_fail('Verify the new email address before saving it.');
}

if ($new !== '') {
    $hash = password_hash($new, PASSWORD_DEFAULT);
    $update = $conn->prepare("UPDATE admin_users SET email = ?, password = ?, must_change_password = 0, password_changed_at = NOW(), failed_attempts = 0, locked_until = NULL WHERE id = ?");
    $update->bind_param("ssi", $email, $hash, $admin_id);
} else {
    $update = $conn->prepare("UPDATE admin_users SET email = ? WHERE id = ?");
    $update->bind_param("si", $email, $admin_id);
}

if (!$update->execute()) {
    $update->close();
    api_fail('Failed to update admin account. Please try again.', 500);
}
$update->close();

$_SESSION['admin_email'] = $email;
if ($new !== '') {
    $_SESSION['admin_must_change'] = 0;
}
api_ok(array('email' => $email));