<?php
function ensure_appointment_reschedule_tokens_schema($conn)
{
    static $ensured = false;
    if ($ensured) {
        return;
    }

    if (!$conn->query("CREATE TABLE IF NOT EXISTS appointment_reschedule_tokens (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        appointment_id INTEGER NOT NULL,
        token_hash VARCHAR(64) NOT NULL UNIQUE,
        expires_at TIMESTAMP NOT NULL,
        used SMALLINT NOT NULL DEFAULT 0,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )")) {
        throw new RuntimeException('Unable to prepare reschedule-link storage: ' . $conn->error);
    }

    $ensured = true;
}

function create_appointment_reschedule_token($conn, $appointment_id)
{
    ensure_appointment_reschedule_tokens_schema($conn);

    $appointment_id = (int)$appointment_id;
    $stmt = $conn->prepare("UPDATE appointment_reschedule_tokens SET used = 1 WHERE appointment_id = ? AND used = 0");
    $stmt->bind_param('i', $appointment_id);
    if (!$stmt->execute()) {
        $error = $stmt->error;
        $stmt->close();
        throw new RuntimeException('Unable to rotate reschedule links: ' . $error);
    }
    $stmt->close();

    $token = bin2hex(random_bytes(32));
    $token_hash = hash('sha256', $token);
    $expires_at = date('Y-m-d H:i:s', time() + (7 * 24 * 60 * 60));
    $stmt = $conn->prepare("INSERT INTO appointment_reschedule_tokens (appointment_id, token_hash, expires_at) VALUES (?, ?, ?)");
    $stmt->bind_param('iss', $appointment_id, $token_hash, $expires_at);
    if (!$stmt->execute()) {
        $error = $stmt->error;
        $stmt->close();
        throw new RuntimeException('Unable to create reschedule link: ' . $error);
    }
    $stmt->close();

    return $token;
}

function find_appointment_reschedule_token($conn, $token)
{
    if (!is_string($token) || !preg_match('/\A[a-f0-9]{64}\z/', $token)) {
        return null;
    }

    ensure_appointment_reschedule_tokens_schema($conn);
    $token_hash = hash('sha256', $token);
    $stmt = $conn->prepare("SELECT appointment_id FROM appointment_reschedule_tokens WHERE token_hash = ? AND used = 0 AND expires_at > NOW()");
    $stmt->bind_param('s', $token_hash);
    if (!$stmt->execute()) {
        $error = $stmt->error;
        $stmt->close();
        throw new RuntimeException('Unable to validate reschedule link: ' . $error);
    }
    $res = $stmt->get_result();
    $row = $res ? $res->fetch_assoc() : null;
    $stmt->close();

    return $row ? ['appointment_id' => (int)$row['appointment_id'], 'token_hash' => $token_hash] : null;
}
