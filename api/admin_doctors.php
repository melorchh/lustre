                        showToast('Doctor updated successfully!', 'success');
                        closeModal('editModal');
                        document.body.classList.add('__leaving');setTimeout(()=>location.reload(),215);
                    } else { showToast(res.trim(), 'error'); }
                })
                .catch(err => { hideLoading(); showToast('Error: ' + err.message, 'error'); });
        });

        // -- Delete -------------------------------------------
        function confirmDelete(btn){
            document.getElementById('deleteDoctorId').value = btn.dataset.id;
            document.getElementById('deleteModalMsg').textContent =
                'Are you sure you want to delete Dr. ' + btn.dataset.name + '? This action cannot be undone.';
            openModal('deleteModal');
        }

        function executeDelete(){
            const id = document.getElementById('deleteDoctorId').value;
            showLoading();
            const fd = new FormData();
            fd.append('action', 'delete');
            fd.append('doctor_id', id);
            fetch('admin_doctor_actions.php', {method:'POST', body:fd})
                .then(r => { if(!r.ok) throw new Error('HTTP ' + r.status + ' ' + r.statusText); return r.text(); })
                .then(res => {
                    hideLoading();
                    if(res.trim() === 'success'){
                        showToast('Doctor deleted!', 'success');
                        closeModal('deleteModal');
                        document.body.classList.add('__leaving');setTimeout(()=>location.reload(),215);
                    } else { showToast(res.trim(), 'error'); }
                })
                .catch(err => { hideLoading(); showToast('Error: ' + err.message, 'error'); });
}

    /* -- Doctor Accounts -- */
    document.getElementById('addAccountForm').addEventListener('submit', function(e){
        e.preventDefault();
        const doctorSel = document.getElementById('acctDoctor');
        const usr = document.getElementById('acctUsername').value.trim();
        const pwd = document.getElementById('acctPassword').value;
        if (!doctorSel.value) { showToast('Please select a doctor', 'error'); return; }
        if (!/^[a-zA-Z0-9_]{3,30}$/.test(usr)) { showToast('Username must be 3-30 characters (letters, numbers, underscore only)', 'error'); return; }
        if (pwd.length < 8) { showToast('Password must be at least 8 characters', 'error'); return; }
        showLoading();
        const fd = new FormData(this);
        fd.append('action', 'add_account');
        fetch('admin_doctor_actions.php', {method:'POST', body:fd})
            .then(r => r.text())
            .then(res => {
                hideLoading();
                if(res.trim() === 'success'){
                    showToast('Doctor account created!','success');
                    document.body.classList.add('__leaving');setTimeout(()=>location.reload(),215);
                } else { showToast(res.trim(), 'error'); }
            })
            .catch(() => { hideLoading(); showToast('Network error','error'); });
    });

