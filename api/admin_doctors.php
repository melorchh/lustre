        function openSidebar(){document.getElementById('adminSidebar').classList.add('open');document.getElementById('sidebarOverlay').classList.add('active');document.body.style.overflow='hidden';}
        function closeSidebar(){document.getElementById('adminSidebar').classList.remove('open');document.getElementById('sidebarOverlay').classList.remove('active');document.body.style.overflow='';}
        function toggleSidebar(){
          var sb=document.getElementById('adminSidebar');
          if(sb.classList.contains('open')){
            sb.classList.remove('open');
            document.getElementById('sidebarOverlay').classList.remove('active');
            document.body.style.overflow='';
          }else{
            sb.classList.add('open');
            if(window.matchMedia('(max-width: 900px)').matches){
              document.getElementById('sidebarOverlay').classList.add('active');
              document.body.style.overflow='hidden';
            }
          }
        }
        function showToast(msg,type=''){const t=document.getElementById('toast');t.textContent=msg;t.className='toast show'+(type?' '+type:'');setTimeout(()=>t.className='toast',3000);}
        function showLoading(){document.getElementById('loadingScreen').classList.add('active');}
        function hideLoading(){document.getElementById('loadingScreen').classList.remove('active');}
        function openModal(id){document.getElementById(id).classList.add('active');}
        function closeModal(id){document.getElementById(id).classList.remove('active');}

        document.querySelectorAll('.modal-overlay').forEach(overlay => {
            overlay.addEventListener('click', function(e){
                if(e.target === this) closeModal(this.id);
            });
        });

        // -- Add ----------------------------------------------
        function openAddModal(){
            document.getElementById('addForm').reset();
            openModal('addModal');
        }

        document.getElementById('addForm').addEventListener('submit', function(e){
            e.preventDefault();
            showLoading();
            const fd = new FormData(this);
            fd.append('action', 'add');
            fetch('admin_doctor_actions.php', {method:'POST', body:fd})
                .then(r => { if(!r.ok) throw new Error('HTTP ' + r.status + ' ' + r.statusText); return r.text(); })
                .then(res => {
                    hideLoading();
                    if(res.trim() === 'success'){
                        showToast('Doctor added successfully!', 'success');
                        closeModal('addModal');
                        document.body.classList.add('__leaving');setTimeout(()=>location.reload(),215);
                    } else { showToast(res.trim(), 'error'); }
                })
                .catch(err => { hideLoading(); showToast('Error: ' + err.message, 'error'); });
        });

        // -- Edit ---------------------------------------------
        function openEditModal(btn){
            document.getElementById('editDoctorId').value    = btn.dataset.id;
            document.getElementById('editName').value        = btn.dataset.name;
            document.getElementById('editSpecialty').value   = btn.dataset.specialty;
            document.getElementById('editSchedule').value    = btn.dataset.schedule;
            document.getElementById('editExperience').value  = btn.dataset.experience;
            openModal('editModal');
        }

        document.getElementById('editForm').addEventListener('submit', function(e){
            e.preventDefault();
            showLoading();
            const fd = new FormData(this);
            fd.append('action', 'edit');
            fetch('admin_doctor_actions.php', {method:'POST', body:fd})
                .then(r => { if(!r.ok) throw new Error('HTTP ' + r.status + ' ' + r.statusText); return r.text(); })
                .then(res => {
                    hideLoading();
